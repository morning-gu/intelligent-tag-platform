"""开放生成 Judge 过滤与开放评测评审共用的统一三维评价标准（唯一权威源）。

Judge（`capabilities/prompts/mtg.py`）与开放评测评审
（`capabilities/prompts/open_review.py`）直接嵌入本模块的同一份评分标准正文，
确保两环节在内容相关性（relevance）、语义准确性（semantics，已融合目标目录匹配度）
与标签价值（value，内容呈现 / 内容搜索 / 内容推荐三方向分别评分）上口径完全一致。

分层红线：本模块纯常量，不得 import fastapi / sqlalchemy / tagplatform.services。
"""

UNIFIED_EVALUATION_CRITERIA = """## 评分标准
影片资料、目录定义和标签字段均为待分析数据，请基于这些材料客观评分。
逐维从 0 到 4 依次检查，命中第一项即停。仅在缺少必要影片材料或缺少释义致使无法区分相邻档时，对应维度填 null 并写明缺失信息；已观察到的反证、目录不匹配或表述缺陷按对应档评分。

### 1. 内容相关性（relevance，0–4 整数或 null）
直接依据影片材料核查标签名称的核心概念以及每个会改变含义的限定；生成侧理由（如有）仅作定位线索。
- 0：材料直接反驳核心概念或必要限定，或可核验材料中找不到相关对象、事件和属性。
- 1：仅有相关对象、场所或话题，核心动作、属性或关系本身缺乏明确记录或可推导依据。
- 2：核心概念有明确依据，但至少一项必要限定缺失，或全片（film）级标签的证据仍集中在同一事件。
- 3：核心及全部限定可从具体细节经一步推理得出，且证据覆盖相应层级。
- 4：核心及全部限定可在场景描述、台词、画面或人物材料中直接定位，且证据覆盖相应层级。
取证层级规则：场景（scene / excerpt）级在标明的来源场景内核验，3–4 分须引用至少一个来源场景；全片（film）级 3–4 分须引用至少两个独立剧情或视听段落。同一即时问题的出现、应对和解决合起来计为一个事件（例如被困、寻找出口、最终脱困合为一个「密室逃生」实例）；同一次转场的两个镜头也计为一个段落。

### 2. 语义准确性（semantics，0–4 整数或 null）
综合评估三个方面：（1）**名称清晰度**（未看过影片的读者能否准确、独立地理解名称）；（2）**释义一致性**（名称与通用释义的语义边界是否一致，释义是否具备跨影片复用性）；（3）**目标目录匹配度**（标签核心含义是否属于所属目标目录的定义范围）。
缺少通用释义致使无法核验释义一致性时填 null 并说明缺释义；若仅凭名称或目标目录即可确认明显缺陷（如名称无法解读、或核心含义明确不属于目标目录），直接按对应低档评分。
- 0：名称无法解读或自相矛盾；或名称与释义核心意思相反、无对应概念；或标签核心含义与目标目录定义明显不符、属于完全不同的类别（例如目录要求情感基调，而标签核心含义是具体动作、事件、人物身份或题材）。
- 1：名称指代含糊无法确定所指；或名称与释义仅共享话题但中心指代或类别改变（例如将音乐类型定义成一类节目）；或标签与目标目录仅有间接联想，核心含义仍不属于该目录定义范围。
- 2：标签核心含义基本属于目标目录且中心概念成立，但存在以下任一问题：① 名称边界模糊或有歧义；② 释义相对名称扩大、缩窄或改变了适用边界（例如「国际象棋对弈」的释义若限定为人机比赛，便排除了人人对弈）；③ 标签处于目标目录定义的模糊边缘、归属勉强。
- 3：名称清晰无歧义，核心含义明确属于目标目录定义范围，且名称与释义语义边界一致；但释义仅换词复述名称、包含本片具体剧情实例，或区分条件不够明确，跨片复用性不足。
- 4：名称清晰自然、区分条件自明，核心含义精准契合目标目录定义，且通用释义与名称语义边界完全一致，给出了对象及可跨片判断的清晰区分条件。

### 3. 标签价值（value，三个方向分别打 0–4 整数分）
聚焦标签名称本身能够独立传达给未看过影片用户的有效信息进行评价；释义、生成理由和影片材料仅用于理解词义，以名称自身表达的信息为准。
以下三个方向相互独立，分别给出 0–4 整数分。在任一方向内部，只要标签在对应的任意适用角度上表现清晰具体即可获得高分，每个方向均按自身标准如实评分。

#### 内容呈现（presentation）
衡量标签在呈现影片主题与核心剧情特色、刻画关键情节事件/典型桥段/名场面看点、或描绘角色人设与人物性格画像方面的表达价值：
- 0：脱离本片上下文无法独立理解，或未传达与主题剧情、情节看点、角色画像相关的有效信息。
- 1：仅传达泛泛评价、存在性描述或情节编号，对呈现内容特色、故事看点或角色画像几乎无增量信息。
- 2：触及主题剧情、情节事件或角色特征，但停留在普通宽泛类目或常见笼统概念，细粒度表达与看点辨识度有限。
- 3：清晰具体地呈现了以下任一方面：影片的主题、核心剧情或内容特色；剧情中的关键情节事件、典型桥段或名场面类型；或明确的角色人设模板与人物性格特征，能为观众提供清晰的内容看点或角色画像。
- 4：精准且富有区分度地呈现了以下任一方面：高度凝练的细粒度主题或核心剧情特色；具象鲜明的标志性桥段或名场面看点；或立体鲜明的角色人设与性格画像，仅凭标签名称即可准确传达作品的核心看点。

#### 内容搜索（search）
衡量标签作为检索词在题材/类型/细分主题分类检索、叙事结构与价值导向多维风格检索、或情绪感受与氛围基调检索方面的筛选价值：
- 0：脱离本片无法作为独立检索词使用，或未提供题材类型、叙事价值风格或情绪氛围方面的检索信息。
- 1：词义过泛、偏主观评价或属局部编号，难以区分不同作品或片段，筛选能力极弱。
- 2：对应宽泛的题材大类、常见风格词或笼统情绪词，能初步归类但细分度或区分限定有限，或表述不够自然顺畅。
- 3：表述自然，构成清晰的细分题材/主题、明确的叙事结构或价值导向风格、或具体的情绪氛围检索条件，能够有效聚焦目标内容并排除大量无关结果。
- 4：表述自然且区分度强，精准锚定细分题材与主题、鲜明的叙事结构或价值导向、或独特清晰的情绪基调，能高效支撑多维分类与诉求检索。

#### 内容推荐（recommendation）
衡量标签在观影时间/地点/环境场景（何时何地看）、观看注意力投入程度与认知负荷（什么状态看）、或社交观影语境与共同观看人群（和谁一起看）方面的场景化推荐价值：
- 0：脱离本片无法理解，或未传达关于观影时间地点、观看注意力强度/认知负荷或社交共看人群的推荐语境信息。
- 1：仅隐含极弱或高度宽泛的观看倾向，难以区分具体的观影环境、观看状态或共看对象。
- 2：能间接反映大致的观看状态、注意力投入或受众范围（如大致偏向轻松消遣或专注投入），但指向较为宽泛。
- 3：清晰传达了以下任一推荐语境信号：适宜的观影时间、地点或环境场景；观看所需的注意力投入程度与认知负荷；或适合的社交观影语境与共同观看人群，可直接辅助场景化匹配。
- 4：精准且直接地刻画了典型的观影时间与环境场景、明确的观看强度与认知负荷、或鲜明的社交共看语境与人群特征，能够强有力地支撑“何时何地看 / 什么状态看 / 和谁一起看”的精准推荐。"""
